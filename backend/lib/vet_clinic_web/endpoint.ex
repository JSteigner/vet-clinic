defmodule VetClinicWeb.Endpoint do
  @moduledoc """
  HTTP and WebSocket entry point for the API.
  """

  use Phoenix.Endpoint, otp_app: :vet_clinic
  use Absinthe.Phoenix.Endpoint

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_vet_clinic_key",
    signing_salt: "eaG3LwrY",
    same_site: "Lax"
  ]

  socket "/socket", VetClinicWeb.UserSocket, websocket: true

  # Test env only (e2e): POST /sandbox starts a database transaction and
  # returns its id; requests whose user agent carries that id run inside it;
  # DELETE /sandbox rolls it back. Never compiled into dev or prod.
  if Application.compile_env(:vet_clinic, :sql_sandbox, false) do
    plug Phoenix.Ecto.SQL.Sandbox, at: "/sandbox", repo: VetClinic.Repo, timeout: 30_000
  end

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :vet_clinic,
    gzip: not code_reloading?,
    only: VetClinicWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :vet_clinic
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug CORSPlug, origin: Application.compile_env(:vet_clinic, :cors_origins, [])
  plug VetClinicWeb.Router
end
